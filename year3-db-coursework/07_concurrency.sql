-- ╔═════════════════════════════════════════════════════════════════╗
-- ║ СЦЕНАРІЙ 1. Явне блокування рядка (SELECT ... FOR UPDATE)        ║
-- ╚═════════════════════════════════════════════════════════════════╝
-- Мета: показати, що зміна рядка чекає завершення транзакції, яка його заблокувала.

-- Сеанс А (залишити транзакцію відкритою!)
BEGIN;
SELECT id, daily_price FROM rental.tools WHERE id = <ID> FOR UPDATE;

-- Сеанс Б: UPDATE того самого рядка очікує сеанс А.
BEGIN;
SET LOCAL lock_timeout = '30s';
UPDATE rental.tools SET daily_price = daily_price + 1 WHERE id = <ID>;   -- «висить»

-- Сеанс В (третє підключення) — побачити блокування:
SELECT pid, state, wait_event_type, wait_event, left(query, 60) AS query
FROM pg_stat_activity
WHERE datname = current_database() AND wait_event_type = 'Lock';
-- Очікується: сеанс Б зі станом active та wait_event = transactionid або tuple.

-- Сеанс А: ROLLBACK;  -> сеанс Б негайно завершує UPDATE; далі в сеансі Б: ROLLBACK;
-- Якщо спливе lock_timeout, сеанс Б отримає помилку 55P03 (lock_not_available) —
-- тоді в сеансі Б також виконайте ROLLBACK.
-- Висновок для записки: блокування рядка не дає двом сеансам одночасно
-- змінювати ту саму ціну; читання (звичайний SELECT) при цьому не блокується.

-- ╔═════════════════════════════════════════════════════════════════╗
-- ║ СЦЕНАРІЙ 2. Подвійна видача того самого інструмента              ║
-- ╚═════════════════════════════════════════════════════════════════╝
-- Бізнес-правило BR04: інструмент не може бути одночасно у двох активних орендах.
-- Захищено частковим унікальним індексом rental_items_one_active_uq.

-- Сеанс А: оформлює оренду, але ще не завершує транзакцію.
BEGIN;
CALL rental.open_rental(1, 1, ARRAY[<ID>], now(), now() + interval '2 days', 'cash', NULL);

-- Сеанс Б: той самий інструмент для іншого клієнта.
BEGIN;
CALL rental.open_rental(2, 2, ARRAY[<ID>], now(), now() + interval '2 days', 'cash', NULL);
-- Сеанс Б ЧЕКАЄ: у індексі є незавершений запис сеансу А з тим самим ключем.

-- Сеанс А: COMMIT;
-- Результат у сеансі Б: ERROR 23505 duplicate key value violates unique constraint
--   "rental_items_one_active_uq". Сеанс Б виконує ROLLBACK.
-- Варіант 2б: якщо в сеансі А виконати ROLLBACK, сеанс Б успішно завершить CALL.
--
-- Висновок: коректність забезпечує обмеження в БД, а не перевірка «спочатку SELECT, потім INSERT»,
-- яка за READ COMMITTED пропустила б обидва сеанси (гонка перевірки та вставки).

-- ╔═════════════════════════════════════════════════════════════════╗
-- ║ СЦЕНАРІЙ 3. Рівень ізоляції (пояснення в записці)                ║
-- ╚═════════════════════════════════════════════════════════════════╝
-- Рівень за замовчуванням — READ COMMITTED: кожен оператор бачить дані, закомічені до
-- його початку. Для правил виду «не більше N активних оренд у клієнта» (залежать від
-- кількох рядків і не виражаються UNIQUE) придатні SERIALIZABLE та повтор транзакції:
--   BEGIN ISOLATION LEVEL SERIALIZABLE;
--   -- перевірити кількість активних позицій клієнта, потім вставити нову
--   COMMIT;   -- може завершитися помилкою 40001 serialization_failure -> транзакцію виконують повторно
-- Атомарність (все або нічого), видимість змін та блокування — різні властивості; їх слід розрізняти.

